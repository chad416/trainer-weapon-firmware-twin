#!/usr/bin/env python3
"""Encode protocol/vectors.json with protocol/trainer.dbc and write the C header
tests/unit/src/proto_vectors.h. The C unit test compares the firmware encoder
against these bytes, so the DBC and the firmware cannot drift apart.

Usage:  python3 protocol/gen_vectors.py            # write the header
        python3 protocol/gen_vectors.py --check    # fail if the header is stale (CI)
"""
import argparse
import json
import pathlib
import sys

import cantools

ROOT = pathlib.Path(__file__).resolve().parent.parent
DBC = ROOT / "protocol" / "trainer.dbc"
VECTORS = ROOT / "protocol" / "vectors.json"
HEADER = ROOT / "tests" / "unit" / "src" / "proto_vectors.h"


def render() -> str:
    db = cantools.database.load_file(str(DBC))
    vectors = json.loads(VECTORS.read_text())["vectors"]
    lines = [
        "/* GENERATED by protocol/gen_vectors.py from protocol/trainer.dbc. Do not edit. */",
        "#ifndef TRAINER_PROTO_VECTORS_H_",
        "#define TRAINER_PROTO_VECTORS_H_",
        "",
        "#include <stdint.h>",
        "",
    ]
    for v in vectors:
        msg = db.get_message_by_name(v["message"])
        data = msg.encode(v["signals"], strict=True)
        hexbytes = ", ".join(f"0x{b:02X}" for b in data)
        lines.append(f"/* {v['message']} (ID 0x{msg.frame_id:03X}): {json.dumps(v['signals'])} */")
        lines.append(f"static const uint8_t VEC_{v['name']}[{len(data)}] = {{{hexbytes}}};")
        lines.append("")
    lines.append("#endif /* TRAINER_PROTO_VECTORS_H_ */")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the header is out of date")
    args = parser.parse_args()

    text = render()
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            print(f"{HEADER} is out of date: run protocol/gen_vectors.py", file=sys.stderr)
            return 1
        print("proto_vectors.h is up to date")
        return 0
    HEADER.write_text(text)
    print(f"wrote {HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
